def _build_scorecard(
    report: SiteReport,
    *,
    is_primary: bool,
    index: int,
) -> dict:
    """Build template context for a single site scorecard."""
    scores = _get_lens_scores(report)
    max_score = _get_max_score(report)
    has_analyst = _has_analyst_scores(report)
    label = _site_label(report.normalized_url)

    ss_uri = None
    if report.screenshots and report.screenshots.viewport:
        ss_uri = _encode_image(report.screenshots.viewport)
    elif report.screenshots and report.screenshots.full_page:
        ss_uri = _encode_image(report.screenshots.full_page)

    pending_note = None
    if not has_analyst:
        pending_note = (
            "Strategic evaluation lenses (Brand & Messaging, Experience & Design, "
            "Conversion & Strategy) are pending analyst review."
        )

    return {
        "label": label,
        "url": report.normalized_url,
        "type_label": "Primary Site" if is_primary else f"Competitor {index}",
        "screenshot_data_uri": ss_uri,
        "score_ring_svg": score_ring(
            report.retina_score.total,
            max_score,
        ),
        "bar_chart_svg": horizontal_bar_chart(scores),
        "pending_note": pending_note,
    }


def _build_analyst_observations(
    analysis: AnalysisRun,
) -> list[list[dict]]:
    """Build analyst observation pages from all reports with analyst scores."""
    pages: list[list[dict]] = []

    all_reports = [analysis.primary_site] + analysis.competitors
    for report in all_reports:
        if not _has_analyst_scores(report):
            continue

        report_lenses: list[dict] = []
        for ls in report.retina_score.lens_scores:
            if ls.is_automated:
                continue

            lens_name = LENS_NAMES_FULL.get(ls.lens.value, ls.lens.value)

            subdims = []
            from retina.scoring.analyst import LENS_DEFINITIONS
            definitions = LENS_DEFINITIONS.get(ls.lens.value, {})
            for dim_key, dim_max in definitions.items():
                dim_score = ls.breakdown.get(dim_key, 0)
                dim_label = dim_key.replace("_", " ").title()
                subdims.append((dim_label, f"{dim_score:.1f}", f"{dim_max:.0f}"))

            ss_uri = None
            if report.screenshots and report.screenshots.analyst_overrides:
                override_path = report.screenshots.analyst_overrides.get(ls.lens.value)
                if override_path:
                    ss_uri = _encode_image(override_path)

            report_lenses.append({
                "lens_name": f"{lens_name} \u2014 {_site_label(report.normalized_url)}",
                "score": f"{ls.score:.1f}",
                "subdimensions": subdims,
                "observations": ls.notes or "",
                "screenshot_uri": ss_uri,
                "lens_color": LENS_COLORS.get(ls.lens.value, "#0066FF"),
            })

        for i in range(0, len(report_lenses), 3):
            pages.append(report_lenses[i : i + 3])

    return pages


def _build_roadmap_sections(analysis: AnalysisRun) -> list[dict]:
    """Build roadmap grouped by quadrant with colored sections."""
    if not analysis.ai_analysis or not analysis.ai_analysis.recommendations:
        return []

    by_quadrant: dict[str, list] = {}
    for rec in analysis.ai_analysis.recommendations:
        q = rec.quadrant.value
        by_quadrant.setdefault(q, []).append(rec)

    sections = []
    for q_key in QUADRANT_PRIORITY:
        recs = by_quadrant.get(q_key, [])
        if not recs:
            continue
        sections.append({
            "label": QUADRANT_LABELS.get(q_key, q_key),
            "color": ROADMAP_QUADRANT_COLORS.get(q_key, "#9BA8B7"),
            "recs": [
                {
                    "title": r.title,
                    "description": _truncate(r.description, 250),
                    "lens": getattr(r, "related_gaps", [""])[0] if r.related_gaps else "",
                }
                for r in recs
            ],
        })

    return sections


def _build_all_lens_pages(
    analysis: AnalysisRun,
    assets_dir: Path,
    lens_icons: dict[str, str],
    screenshot_uri: str | None = None,
    subdim_observations: dict[str, dict[str, str]] | None = None,
) -> list[dict]:
    """Build data for ALL lens pages (automated + analyst).

    Creates a page for each of the 5 lenses in LENS_ORDER. For analyst lenses,
    sub-dimension definitions come from LENS_DEFINITIONS. For automated lenses,
    sub-dimensions are derived from the breakdown dict with a default max of 5.0.

    Args:
        analysis: The analysis run.
        assets_dir: Path to assets directory.
        lens_icons: Dict of lens_key -> SVG string for icons.
        screenshot_uri: Data URI for the site screenshot.
        subdim_observations: Optional dict of {lens_key: {subdim_key: observation_text}}.

    Returns:
        List of dicts, one per lens page, ordered by LENS_ORDER.
    """
    from retina.scoring.analyst import LENS_DEFINITIONS

    pages: list[dict] = []
    primary = analysis.primary_site
    obs_map = subdim_observations or {}

    # Index lens scores by key for ordered iteration
    ls_by_key: dict[str, object] = {}
    for ls in primary.retina_score.lens_scores:
        ls_by_key[ls.lens.value] = ls

    for lens_key in LENS_ORDER:
        ls = ls_by_key.get(lens_key)
        if ls is None:
            continue

        color = LENS_COLORS.get(lens_key, "#0066FF")
        name = LENS_NAMES_FULL.get(lens_key, lens_key)
        subtitle = LENS_SUBTITLES.get(lens_key, "")

        # Score ring for this lens (score/20)
        ring_svg = score_ring(
            ls.score, 20.0,
            size=100, stroke_width=8,
            color=color, show_max=True,
        )

        # Overall observations from notes
        observations = ls.notes or ""
        observation_paragraphs = [
            p.strip() for p in observations.split("\n\n") if p.strip()
        ] if observations else []

        # Sub-dimensions: use LENS_DEFINITIONS for analyst lenses,
        # fall back to breakdown keys for automated lenses
        definitions = LENS_DEFINITIONS.get(lens_key, {})
        lens_obs = obs_map.get(lens_key, {})
        subdimensions = []

        if definitions:
            # Analyst lens — use formal definitions
            for dim_key, dim_max in definitions.items():
                dim_score = ls.breakdown.get(dim_key, 0.0)
                dim_name = SUBDIM_DISPLAY_NAMES.get(
                    dim_key, dim_key.replace("_", " ").title()
                )
                dim_observation = lens_obs.get(dim_key, "")

                dim_ring_svg = score_ring(
                    dim_score, dim_max,
                    size=56, stroke_width=5,
                    color=color, show_max=True,
                )

                subdimensions.append({
                    "name": dim_name,
                    "score": dim_score,
                    "max_score": dim_max,
                    "ring_svg": dim_ring_svg,
                    "observation": dim_observation,
                })
        else:
            # Automated lens — derive from breakdown dict
            for dim_key, dim_score in ls.breakdown.items():
                dim_max = 5.0  # default max per sub-dimension
                dim_name = SUBDIM_DISPLAY_NAMES.get(
                    dim_key, dim_key.replace("_", " ").title()
                )
                dim_observation = lens_obs.get(dim_key, "")

                dim_ring_svg = score_ring(
                    dim_score, dim_max,
                    size=56, stroke_width=5,
                    color=color, show_max=True,
                )

                subdimensions.append({
                    "name": dim_name,
                    "score": dim_score,
                    "max_score": dim_max,
                    "ring_svg": dim_ring_svg,
                    "observation": dim_observation,
                })

        pages.append({
            "lens_key": lens_key,
            "name": name,
            "color": color,
            "subtitle": subtitle,
            "is_automated": ls.is_automated,
            "icon_svg": lens_icons.get(lens_key, ""),
            "score_ring_svg": ring_svg,
            "screenshot_uri": screenshot_uri,
            "observations": observations,
            "observation_paragraphs": observation_paragraphs,
            "subdimensions": subdimensions,
        })

    return pages


def _build_tech_summary(analysis: AnalysisRun) -> list[tuple[str, str]]:
    """Extract a concise tech stack summary: [(category_label, names_str), ...]."""
    if not analysis.primary_site.tech_stack:
        return []

    by_cat: dict[str, list[str]] = {}
    for tech in analysis.primary_site.tech_stack.technologies:
        override = TECH_NAME_OVERRIDES.get(tech.name)
        if override:
            by_cat.setdefault(override, [])
            if tech.name not in by_cat[override]:
                by_cat[override].append(tech.name)
            continue

        for cat in tech.categories:
            mapped = TECH_CATEGORY_MAP.get(cat)
            if mapped:
                by_cat.setdefault(mapped, [])
                if tech.name not in by_cat[mapped]:
                    by_cat[mapped].append(tech.name)
                break

    result = []
    for cat in ["CMS", "Analytics", "CRM", "Framework"]:
        names = by_cat.get(cat, [])
        if names:
            result.append((cat, ", ".join(names[:5])))

    return result


def _build_tech_stack_full(analysis: AnalysisRun) -> dict[str, list[str]]:
    """Build the full technology stack grouped by category."""
    if not analysis.primary_site.tech_stack:
        return {}

    by_cat: dict[str, list[str]] = {}
    for tech in analysis.primary_site.tech_stack.technologies:
        assigned = False
        override = TECH_NAME_OVERRIDES.get(tech.name)
        if override:
            by_cat.setdefault(override, [])
            if tech.name not in by_cat[override]:
                by_cat[override].append(tech.name)
            assigned = True

        if not assigned:
            for cat in tech.categories:
                mapped = TECH_CATEGORY_MAP.get(cat)
                if mapped:
                    by_cat.setdefault(mapped, [])
                    if tech.name not in by_cat[mapped]:
                        by_cat[mapped].append(tech.name)
                    assigned = True
                    break

        if not assigned and tech.categories:
            cat_name = tech.categories[0]
            by_cat.setdefault(cat_name, [])
            if tech.name not in by_cat[cat_name]:
                by_cat[cat_name].append(tech.name)

    return by_cat


