def _encode_image(source: str | Path | bytes, *, mime: str | None = None) -> str | None:
    """Encode an image as a base64 data URI for inline embedding.

    Accepts either a file path (str/Path) or raw bytes.
    Returns a ``data:<mime>;base64,...`` string, or None if the source
    is unavailable.

    Args:
        source: Local file path, or raw image bytes.
        mime: Explicit MIME type. Inferred from file extension when
              *source* is a path; defaults to ``image/png`` for bytes.
    """
    if isinstance(source, bytes):
        if not source:
            return None
        mime = mime or "image/png"
        b64 = base64.b64encode(source).decode("ascii")
        return f"data:{mime};base64,{b64}"

    # File-path branch
    p = Path(source)
    if not p.exists():
        logger.warning("Image not found: %s", p)
        return None
    if mime is None:
        suffix = p.suffix.lower()
        mime = {
            ".png": "image/png",
            ".jpg": "image/jpeg",
            ".jpeg": "image/jpeg",
            ".svg": "image/svg+xml",
            ".webp": "image/webp",
        }.get(suffix, "image/png")
    data = p.read_bytes()
    b64 = base64.b64encode(data).decode("ascii")
    return f"data:{mime};base64,{b64}"


def fetch_screenshot_bytes(url: str) -> bytes | None:
    """Download a screenshot image from a URL and return raw bytes.

    Uses a synchronous HTTP client with a 15-second timeout.
    Returns None on any failure (network error, non-200 status, etc.).
    """
    try:
        import httpx
        with httpx.Client(follow_redirects=True) as client:
            response = client.get(url, timeout=15)
            if response.status_code == 200:
                return response.content
    except Exception as e:
        logger.warning("Screenshot fetch failed for %s: %s", url, e)
    return None


def _mime_from_url(url: str) -> str:
    """Guess MIME type from a URL's extension."""
    lower = url.lower().split("?")[0]
    if lower.endswith(".jpg") or lower.endswith(".jpeg"):
        return "image/jpeg"
    if lower.endswith(".webp"):
        return "image/webp"
    return "image/png"


def _read_svg(path: str | Path) -> str | None:
    """Read an SVG file and return its content, or None if missing."""
    p = Path(path)
    if not p.exists():
        return None
    return p.read_text(encoding="utf-8")


def _get_lens_scores(report: SiteReport) -> dict[str, float | None]:
    """Extract a dict of lens_key -> score from a SiteReport."""
    scores: dict[str, float | None] = {}
    scored_keys = set()
    for ls in report.retina_score.lens_scores:
        scores[ls.lens.value] = ls.score
        scored_keys.add(ls.lens.value)
    for key in LENS_ORDER:
        if key not in scored_keys:
            scores[key] = None
    return scores


def _has_analyst_scores(report: SiteReport) -> bool:
    """Check if a report has any analyst-scored lenses."""
    return any(not ls.is_automated for ls in report.retina_score.lens_scores)


def _get_max_score(report: SiteReport) -> float:
    """Determine max possible score based on which lenses are present."""
    return 100.0 if _has_analyst_scores(report) else 40.0


def _truncate(text: str, max_len: int = 200) -> str:
    """Truncate text to max_len, adding ellipsis if needed."""
    if len(text) <= max_len:
        return text
    return text[: max_len - 3] + "..."


def _site_label(url: str) -> str:
    """Extract a readable label from a URL."""
    from urllib.parse import urlparse
    parsed = urlparse(url)
    return parsed.netloc or url


