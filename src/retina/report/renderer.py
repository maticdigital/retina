def _safe_svg_white(svg_str: str) -> str:
    """Convert dark SVG fills to white for dark backgrounds."""
    if not svg_str:
        return ""
    return (
        svg_str
        .replace('fill="#000227"', 'fill="#FFFFFF"')
        .replace('fill="#0A0E27"', 'fill="#FFFFFF"')
        .replace('fill="#1A1A2E"', 'fill="#FFFFFF"')
    )


