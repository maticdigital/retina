def render_pdf(
    analysis: AnalysisRun,
    output_path: str | Path,
    *,
    assets_dir: str | Path = "assets",
    interpretations: dict[str, dict] | None = None,
    analyst_name: str | None = None,
    project_title: str | None = None,
    subdim_observations: dict[str, dict[str, str]] | None = None,
    screenshot_data_uri: str | None = None,
) -> Path:
    """Render a complete PDF report from an AnalysisRun.

    Args:
        analysis: The completed analysis run with all data.
        output_path: Where to save the PDF.
        assets_dir: Path to the assets directory for logos.
        interpretations: Optional dict mapping site URLs to interpretation dicts.
        analyst_name: Name of the analyst for the summary page.
        project_title: Display name for the project (falls back to site label).
        subdim_observations: Per-lens per-subdim observation text.
        screenshot_data_uri: Pre-encoded screenshot data URI. When provided,
            takes priority over ScreenshotData file paths. Pass None to omit
            the screenshot entirely.

    Returns:
        Path to the generated PDF.
    """
    # Guarantee native libs are discoverable in this thread/process
    _ensure_weasyprint_libs()

    from weasyprint import HTML

    output_path = Path(output_path)
    assets_dir = Path(assets_dir)

    # Load logos and icons
    retina_logo = _read_svg(assets_dir / "Matic-Retina.svg")
    matic_logo = _read_svg(assets_dir / "Matic-Logo.svg")

    lens_icons = {}
    icon_files = {
        "performance_technical_health": "performance_icon.svg",
        "seo_ai_visibility": "seo_icon.svg",
        "brand_messaging": "brand_icon.svg",
        "experience_design": "experience_icon.svg",
        "conversion_strategy": "conversion_icon.svg",
    }
    for lens_key, filename in icon_files.items():
        lens_icons[lens_key] = _read_svg(assets_dir / filename) or ""

    # Primary site info
    primary = analysis.primary_site
    competitors = analysis.competitors

    # Project title
    title = project_title or _site_label(primary.normalized_url)

    # Executive summary
    exec_summary = ""
    exec_paragraphs = []
    if analysis.ai_analysis and analysis.ai_analysis.executive_summary:
        exec_summary = analysis.ai_analysis.executive_summary
        exec_paragraphs = [p.strip() for p in exec_summary.split("\n\n") if p.strip()]

    # Lens scores for charts
    lens_scores = _get_lens_scores(primary)
    lens_scores_float = {k: (v or 0) for k, v in lens_scores.items()}
    max_score = _get_max_score(primary)

    # Segmented donut chart
    donut_svg = segmented_donut(lens_scores_float, primary.retina_score.total)

    # Summary bar chart
    summary_bar_svg = horizontal_bar_chart(lens_scores)

    # Screenshot: prefer explicit data URI > viewport path > full-page path
    primary_ss_uri = screenshot_data_uri
    if not primary_ss_uri and primary.screenshots and primary.screenshots.viewport:
        primary_ss_uri = _encode_image(primary.screenshots.viewport)
    if not primary_ss_uri and primary.screenshots and primary.screenshots.full_page:
        primary_ss_uri = _encode_image(primary.screenshots.full_page)

    # Tech stack summary
    tech_summary = _build_tech_summary(analysis)

    # Recommendations
    has_recs = bool(
        analysis.ai_analysis
        and analysis.ai_analysis.recommendations
    )

    recommendation_quadrants = []
    if has_recs:
        quad_config = [
            ("no_brainer", "No-Brainers", "Low effort, high impact", Q_NO_BRAINER),
            ("growth_move", "Growth Moves", "High effort, high impact", Q_GROWTH),
            ("quick_win", "Quick Wins", "Low effort, lower impact", Q_QUICK_WIN),
            ("transformational", "Transformational", "High effort, long-term payoff", Q_TRANSFORM),
        ]
        by_q: dict[str, list] = {}
        for rec in analysis.ai_analysis.recommendations:
            by_q.setdefault(rec.quadrant.value, []).append(rec)

        for q_key, label, desc, color in quad_config:
            recs = by_q.get(q_key, [])
            recommendation_quadrants.append({
                "label": label,
                "descriptor": desc,
                "color": color,
                "recs": [
                    {
                        "title": r.title,
                        "description": r.description or "",
                        "lens_color": LENS_COLORS.get(
                            r.related_gaps[0], None
                        ) if r.related_gaps else None,
                        "lens_name": LENS_BADGE_NAMES.get(
                            r.related_gaps[0], ""
                        ) if r.related_gaps else "",
                    }
                    for r in recs
                ],
            })

    # All lens pages (automated + analyst)
    analyst_lens_pages = _build_all_lens_pages(
        analysis,
        assets_dir,
        lens_icons,
        screenshot_uri=primary_ss_uri,
        subdim_observations=subdim_observations,
    )

    # Build template context
    context = {
        "retina_logo_svg": retina_logo,
        "matic_logo_svg": matic_logo,
        "lens_icons": lens_icons,
        "primary_url": primary.normalized_url,
        "project_title": title,
        "analysis_date": analysis.created_at.strftime("%m.%d.%Y"),
        "analyst_name": analyst_name,
        "donut_chart_svg": donut_svg,
        "summary_bar_chart_svg": summary_bar_svg,
        "screenshot_data_uri": primary_ss_uri,
        "tech_summary": tech_summary,
        "executive_summary": exec_summary,
        "executive_summary_paragraphs": exec_paragraphs,
        "lens_descriptions": LENS_DESCRIPTIONS,
        "lens_names": LENS_NAMES_FULL,
        "lens_order": LENS_ORDER,
        "analyst_lens_pages": analyst_lens_pages,
        "has_recommendations": has_recs,
        "recommendation_quadrants": recommendation_quadrants,
        "quadrant_labels": QUADRANT_LABELS,
        "quadrant_colors": QUADRANT_COLORS,
    }

    # Render HTML
    env = Environment(loader=BaseLoader(), autoescape=False)
    env.filters["safe_svg_white"] = _safe_svg_white
    template = env.from_string(REPORT_TEMPLATE)
    html_content = template.render(**context)

    # Convert to PDF
    logger.info("Generating PDF report: %s", output_path)
    html_doc = HTML(string=html_content)
    html_doc.write_pdf(str(output_path))

    logger.info("PDF report saved: %s (%d bytes)", output_path, output_path.stat().st_size)
    return output_path
